import os                                 # Подключаем модуль для работы с файлами (проверка существования)
import sys                                # Подключаем модуль sys — он даёт доступ к аргументам из терминала

# --- НАСТРОЙКИ (минимальные, только имя выходного файла) ---
output_filename = "cli_report.txt"        # Имя файла, куда запишем отчёт. Меняй тут, если нужно

def process_files(files_list):            # Функция принимает список файлов и возвращает строки отчёта
    """Проверяет файлы и возвращает список строк отчёта."""
    report_lines = []                     # Пустой список — сюда будем складывать строки
    report_lines.append("📁 ОТЧЁТ (через CLI)")  # Заголовок отчёта
    report_lines.append("-" * 30)          # Разделитель из 30 тире
    
    for file_name in files_list:           # Проходим по каждому файлу из переданного списка
        exists = os.path.exists(file_name)  # Проверяем: файл реально есть на диске? (True/False)
        
        if exists:                         # Если файл есть:
            line = f"✅ {file_name} — найден"  # Формируем строку с галочкой
        else:                              # Если файла нет:
            line = f"❌ {file_name} — НЕ найден"  # Формируем строку с крестиком
        
        report_lines.append(line)          # Добавляем строку в наш список отчёта
    
    return report_lines                    # Возвращаем весь список строк наружу

# --- ОСНОВНАЯ ЛОГИКА (читаем аргументы из терминала) ---

# sys.argv — это список всего, что ты ввёл в терминале.
# Пример: python3 practice_cli_simple.py README.md Dockerfile
# Тогда sys.argv будет: ['practice_cli_simple.py', 'README.md', 'Dockerfile']
#
# [1:] означает «взять всё, начиная со второго элемента» (пропустить имя скрипта).
files_from_cli = sys.argv[1:]              # Получаем список файлов прямо из командной строки

# Если пользователь ничего не передал (запустил просто python3 script.py),
# files_from_cli будет пустым списком [].
# Чтобы скрипт не упал, зададим запасной список по умолчанию.
if len(files_from_cli) == 0:
    files_to_check = ["README.md", "Dockerfile"]  # Файлы по умолчанию, если ничего не передали
else:
    files_to_check = files_from_cli       # Иначе используем то, что передали в терминале

# Вызываем функцию проверки, передавая ей список файлов
report = process_files(files_to_check)

# Записываем отчёт в файл (имя берём из переменной output_filename)
with open(output_filename, "w", encoding="utf-8") as f:
    for line in report:                   # Проходим по каждой строке отчёта
        f.write(line + "\n")              # Пишем строку и добавляем перенос строки (\n)

print(f"💾 Готово! Отчёт сохранён в: {output_filename}")  # Сообщаем, где лежит результат
print(f"📂 Проверено файлов: {len(files_to_check)}")      # Показываем, сколько файлов проверили

