import os                                      # Подключаем встроенный модуль os — он умеет проверять, есть ли файл на диске

# --- НАСТРОЙКИ (это "верхний уровень", отсюда всё начинается) ---
output_filename = "my_simple_report_test.txt"      # Имя файла, куда запишем отчёт. Меняй тут — весь скрипт подстроится
files_to_check = ["README.md", "hello_vars.py", "requirements.txt"]  # Список файлов, которые будем проверять

def process_files(files_list):                 # Функция принимает один аргумент — список файлов (files_list)
    """Проверяет файлы и возвращает список строк отчёта."""
    report_lines = []                           # Пустой список — сюда будем складывать строки по одной
    report_lines.append("📁 ПРОСТОЙ ОТЧЁТ")    # Добавляем заголовок
    report_lines.append("-" * 30)              # Добавляем разделитель (30 тире)
    
    for file_name in files_list:                # Берём каждый файл из списка по очереди
        exists = os.path.exists(file_name)      # Проверяем, есть ли он на диске (True/False)
        
        if exists:                             # Если есть:
            line = f"✅ {file_name} — найден"   # Формируем строку с галочкой
        else:                                  # Если нет:
            line = f"❌ {file_name} — НЕ найден" # Формируем строку с крестиком
        
        report_lines.append(line)              # Кладём готовую строку в список
    
    return report_lines                         # Отдаём весь список наружу — это результат функции

# --- ОСНОВНАЯ ЛОГИКА (здесь используем то, что объявлено наверху) ---
report = process_files(files_to_check)         # Вызываем функцию, передаём ей список файлов, результат кладём в report

with open(output_filename, "w", encoding="utf-8") as f:  # Открываем файл на запись ("w"), with сам его закроет
    for line in report:                         # Берём каждую строку из отчёта
        f.write(line + "\n")                    # Пишем строку + перенос на новую строку (\n)

print(f"💾 Готово! Отчёт сохранён в: {output_filename}")  # Сообщаем, где лежит результат

